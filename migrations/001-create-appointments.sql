CREATE TABLE public.appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    service TEXT NOT NULL,
    appointment_date DATE NOT NULL,
    status TEXT NOT NULL DEFAULT 'requested'
        CHECK (status IN ('requested', 'confirmed', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    cancellation_token_hash TEXT
);

CREATE INDEX appointments_date_idx
    ON public.appointments (appointment_date);

CREATE UNIQUE INDEX appointments_cancellation_token_idx
    ON public.appointments (cancellation_token_hash)
    WHERE cancellation_token_hash IS NOT NULL;
