const assert = require("node:assert/strict");
const crypto = require("node:crypto");
const process = require("node:process");
const path = require("node:path");
const { Pool } = require("pg");
const { createPostgresAppointmentStore, createServer } = require("../server");

function loadLocalEnvironment() {
    try {
        process.loadEnvFile(path.join(__dirname, "..", ".env.local"));
    } catch (error) {
        if (error.code !== "ENOENT") throw error;
    }
}

function nextDate() {
    const date = new Date();
    date.setDate(date.getDate() + 1);
    return [
        date.getFullYear(),
        String(date.getMonth() + 1).padStart(2, "0"),
        String(date.getDate()).padStart(2, "0"),
    ].join("-");
}

async function listen(server) {
    await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
    return `http://127.0.0.1:${server.address().port}`;
}

async function close(server) {
    await new Promise((resolve, reject) => {
        server.close((error) => error ? reject(error) : resolve());
    });
}

async function main() {
    loadLocalEnvironment();
    const connectionString = process.env.DATABASE_URL_UNPOOLED;
    if (!connectionString) throw new Error("DATABASE_URL_UNPOOLED is required for the Neon integration test.");

    const pool = new Pool({ connectionString, max: 1, connectionTimeoutMillis: 10_000 });
    const client = await pool.connect();
    let server;
    let transactionStarted = false;

    try {
        await client.query("BEGIN");
        transactionStarted = true;
        await client.query(`
            CREATE TEMP TABLE appointments (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                phone TEXT NOT NULL,
                service TEXT NOT NULL,
                appointment_date DATE NOT NULL,
                status TEXT NOT NULL DEFAULT 'requested'
                    CHECK (status IN ('requested', 'confirmed', 'cancelled')),
                created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
                cancellation_token_hash TEXT
            )
        `);

        const postgresStore = createPostgresAppointmentStore(client);
        const testStore = { ...postgresStore, async close() {} };
        const appointmentDate = nextDate();
        const salt = crypto.randomBytes(16);
        const password = "Neon-integration-test-password";
        const passwordHash = `scrypt$16384$${salt.toString("hex")}$${crypto.scryptSync(
            password,
            salt,
            64,
            { N: 16384, maxmem: 64 * 1024 * 1024 },
        ).toString("hex")}`;
        server = createServer({
            appointmentStore: testStore,
            adminUsername: "integration-test-admin",
            adminPasswordHash: passwordHash,
        });
        const origin = await listen(server);

        const bookingResponse = await fetch(`${origin}/api/appointments`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
                name: "Neon Integration Test",
                phone: "5550100100",
                service: "The classic cut",
                appointmentDate,
            }),
        });
        assert.equal(bookingResponse.status, 201);
        const booking = await bookingResponse.json();

        const deniedAdminRead = await fetch(`${origin}/api/admin/appointments`);
        assert.equal(deniedAdminRead.status, 401);

        const login = await fetch(`${origin}/api/admin/login`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ username: "integration-test-admin", password }),
        });
        assert.equal(login.status, 200);
        const cookie = login.headers.get("set-cookie").split(";")[0];
        const { csrfToken } = await login.json();

        const appointmentsResponse = await fetch(
            `${origin}/api/admin/appointments?search=Neon+Integration+Test`,
            { headers: { Cookie: cookie } },
        );
        assert.equal(appointmentsResponse.status, 200);
        const dashboard = await appointmentsResponse.json();
        assert.equal(dashboard.appointments.length, 1);
        assert.equal(dashboard.appointments[0].name, "Neon Integration Test");
        assert.equal(dashboard.appointments[0].appointment_date, appointmentDate);
        assert.equal(dashboard.stats.pending, 1);

        const statusResponse = await fetch(`${origin}/api/admin/appointments/${booking.id}/status`, {
            method: "PATCH",
            headers: {
                "Content-Type": "application/json",
                Cookie: cookie,
                "x-csrf-token": csrfToken,
            },
            body: JSON.stringify({ status: "confirmed" }),
        });
        assert.equal(statusResponse.status, 200);

        const cancellationResponse = await fetch(`${origin}/api/appointments/${booking.id}/cancel`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ cancellationToken: booking.cancellationToken }),
        });
        assert.equal(cancellationResponse.status, 200);

        const finalDashboardResponse = await fetch(
            `${origin}/api/admin/appointments?search=Neon+Integration+Test`,
            { headers: { Cookie: cookie } },
        );
        const finalDashboard = await finalDashboardResponse.json();
        assert.equal(finalDashboard.appointments[0].status, "cancelled");
        assert.equal(finalDashboard.stats.cancelled, 1);

        const replayResponse = await fetch(`${origin}/api/appointments/${booking.id}/cancel`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ cancellationToken: booking.cancellationToken }),
        });
        assert.equal(replayResponse.status, 404);

        await close(server);
        server = null;
        await client.query("ROLLBACK");
        transactionStarted = false;
        console.log("Neon PostgreSQL API integration passed; its temporary table and test appointment were rolled back.");
    } finally {
        if (server) await close(server);
        if (transactionStarted) await client.query("ROLLBACK");
        client.release();
        await pool.end();
    }
}

main().catch((error) => {
    console.error(`Neon integration test failed: ${error.message}`);
    process.exitCode = 1;
});
